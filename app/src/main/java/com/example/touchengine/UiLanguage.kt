enum class AppLanguage(val code: String, val badge: String) {
    CHINESE("zh", "中"),
    JAPANESE("ja", "日"),
    ENGLISH("en", "EN");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code == code } ?: CHINESE

        fun defaultForSystemLocale(locale: Locale): AppLanguage = when (locale.language.lowercase()) {
            "zh" -> CHINESE
            "ja" -> JAPANESE
            "en" -> ENGLISH
            else -> ENGLISH
        }

        fun savedOrSystemDefault(savedCode: String?, locale: Locale): AppLanguage =
            if (savedCode.isNullOrBlank()) defaultForSystemLocale(locale) else fromCode(savedCode)
    }
}

